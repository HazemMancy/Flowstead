# Usage: python3 -I benchmarks/tools/make_expected.py <case-dir> [<case-dir> ...]
#
# Solves each case's input.json with the engine worker and writes expected.json with
# "source": "engine-provisional" (decision D6). Any "reference" block already present in
# expected.json (independent values: IAPWS, NIST, HYSYS, desktop DWSIM) is kept as is.
# Provisional values only prove the engine is repeatable; replace them with desktop-DWSIM or
# HYSYS numbers when available and change "source" accordingly.

import datetime
import json
import os
import subprocess
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
WORKER = os.path.join(ROOT, "engine/src/ThermoDock.Engine.Worker/bin/Release/net8.0/linux-x64/ThermoDock.Engine.Worker.dll")

# Tolerances from the brief: ±0.01 °C on temperature, ±0.1 % relative elsewhere.
TOL = {
    "temperature": {"abs": 0.01},
    "vapourFraction": {"abs": 1e-4},
    "phaseMoleFraction": {"abs": 1e-4},
}
DEFAULT_TOL = {"rel": 1e-3, "abs": 1e-9}
COMPOSITION_TOL = {"abs": 1e-4}
STREAM_KEYS = ["temperature", "pressure", "vapourFraction", "molarFlow", "massFlow", "massEnthalpy"]
PHASE_KEYS = ["phaseMoleFraction", "density", "molecularWeight", "massEnthalpy"]
UNITOP_KEYS = ["duty", "pressureDrop", "outletPressure", "outletTemperature", "power",
               "pressureGradient", "maxVelocity", "maxMomentumFlux", "liquidHoldup"]


def solve(flowsheet):
    req = json.dumps({"id": 1, "method": "solve", "params": flowsheet}) + "\n"
    out = subprocess.run(["dotnet", WORKER], input=req, capture_output=True, text=True, check=True).stdout
    lines = [json.loads(l) for l in out.splitlines() if l.strip()]
    resp = next(l for l in lines if l["id"] == 1)
    if resp.get("error"):
        raise SystemExit(resp["error"])
    ready = next(l for l in lines if l["id"] == 0)["result"]
    return resp["result"], ready["dwsimVersion"]


def checks_for(result):
    checks = []
    for oid, obj in result["objects"].items():
        props = obj["properties"]
        keys = STREAM_KEYS if obj.get("phases") is not None else UNITOP_KEYS
        for k in keys:
            if k in props:
                checks.append({"path": f"objects.{oid}.properties.{k}", "expected": props[k], "tol": TOL.get(k, DEFAULT_TOL)})
        for ph, pr in (obj.get("phases") or {}).items():
            for k in PHASE_KEYS:
                if k in pr["properties"]:
                    checks.append({"path": f"objects.{oid}.phases.{ph}.properties.{k}", "expected": pr["properties"][k],
                                   "tol": TOL.get(k, DEFAULT_TOL)})
            for c, x in pr["composition"].items():
                checks.append({"path": f"objects.{oid}.phases.{ph}.composition.{c}", "expected": x, "tol": COMPOSITION_TOL})
    return checks


def main(dirs):
    for d in dirs:
        case = json.load(open(os.path.join(d, "input.json"), encoding="utf-8"))
        result, dwsim = solve(case["flowsheet"])
        if result["status"] != "converged":
            raise SystemExit(f"{d}: engine did not converge: {result['messages']}")
        path = os.path.join(d, "expected.json")
        old = json.load(open(path, encoding="utf-8")) if os.path.exists(path) else {}
        expected = {
            "source": "engine-provisional",
            "note": "Generated by the ThermoDock engine itself: proves repeatability, not correctness. "
                    "Replace with desktop-DWSIM or HYSYS values when available (docs/DECISIONS.md D6).",
            "generatedWith": {"engine": result["engineVersion"], "dwsim": dwsim,
                              "date": datetime.date.today().isoformat()},
            "status": "converged",
            "checks": checks_for(result),
            "reference": old.get("reference", []),
        }
        with open(path, "w", encoding="utf-8") as f:
            json.dump(expected, f, indent=2, ensure_ascii=False)
            f.write("\n")
        print(f"{d}: {len(expected['checks'])} checks, {len(expected['reference'])} reference values")


if __name__ == "__main__":
    main(sys.argv[1:] or sys.exit(__doc__))
